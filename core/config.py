def cfg(*keys, default=None):
    """按路径取配置：`cfg("recall", "inject_n")`。

    给业务代码一个短入口，避免到处写 `CONFIG["recall"]["inject_n"]`
    这种长串——长串抄错一个键名不会报错，只会静默取到 None。
    """
    node = CONFIG
    for k in keys:
        if not isinstance(node, dict) or k not in node:
            return default
        node = node[k]
    return node


def abspath(rel: str) -> Path:
    """把配置里的相对路径解析成基于项目根目录的绝对路径。"""
    p = Path(rel)
    return p if p.is_absolute() else (ROOT / p)


def db_path() -> Path:
    """库文件路径。`CONFIG.db_path` 优先、`PATHS.db` 兜底——
    两个都要的原因只有一个：测试会临时改前者。
    """
    return abspath(cfg("db_path") or PATHS["db"])


def ensure_dirs() -> None:
    """确保运行期目录存在（data / trace / backups / self）。

    每次都建是刻意的：`data/` 不进版本库，新克隆下来是空的，
    与其在每个写入点判断目录存不存在，不如启动时统一建一次。
    """
    for rel in (PATHS["data_dir"], PATHS["trace_dir"], PATHS["backup_dir"],
                PATHS["self_dir"], PATHS["raws_dir"]):
        abspath(rel).mkdir(parents=True, exist_ok=True)


