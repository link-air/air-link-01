"""air-link-01 记忆系统的核心包。

这个系统只做一件事：**记住一段关系，并在该想起的时候想起它。**
记的对象不是「用户档案」，而是「这段互动」——所以下面每个模块都只负责
这条链路的一小段：

    一句话进来
      → 短期记忆管住正在发生的这段（切话题、超预算就提取）
      → 提取 = 场景卡落库 + 原文落文档（S0→S1）
      → 谈得多了，聚合、抽象、印证、修正、老化（S1→S2→S3）
      → 下一句进来时被线索唤起（含原文下钻）
      → 未了结的事进备忘录，到期给一道门
      → 另有她的手（工具箱）和他能翻的口子（打捞）

改任何一处之前先看下面这张地图。

一、分层（只能往上依赖，不能往下回头看）
    L11 dashboard     界面：本地仪表盘（HTTP + 前端），唯一把所有层拼起来的地方
    L10 chat          对话层：把记忆接进一次真实对话
     ├ L9  tools      她的手（三档权限 + 红线终审 + 留痕）
     ├ L9  webfetch   取网页：`web` 的 url 分支实现（URL 校验 / 只许公共地址 / 连接固定 / 同源重定向）
     ├ L9  weave      编织层：镜像呈现 + 可否决 + 人确认后才动的那些改动（原 R6）
     ├ L9  salvage    打捞：人主动从原文里找回一件东西
     ├ L9  trend      渐变检测：一直在提，但内容在慢慢变
     ├ L8  memo       备忘录：到点 → 进注入（提一次就停）→ 闭合 → 退役
     ├ L7  recall     唤醒引擎：七条线索 → 动作 → 抑制 → 注入 + trace
     ├ L6  shortterm  短期记忆：窗口管理、压缩=提取、四条触发
     ├ L5  distill    提炼流水线：S0→S1→S2→S3 + 印证收敛 + 修正 + 老化
     ├ L4  scene      场景切分 + 字段抽取 + 行为强度
     ├ L4  entity     实体索引与旁路（消歧）
     ├ L3  persona    人格文件（self/personas/*.md）：读 / 列 / 写 / 停用 + 留痕
     ├ L3  prompts    所有提示词与输出 schema（不散落在业务逻辑里）
     ├ L2  llm        LLM 调用：JSON schema 约束 + 重试 + 降级
     ├ L2  search     搜索通道表：换一家 = 换配置，加一种形态 = 加一条描述（`llm.search` 的按图索骥处）
     ├ L2  embedding  语义向量服务（带字符重叠兜底）
     ├ L2  settings   敏感配置的优先级链（默认 < AIR2_* < 本地文件 < AIR_LINK_*）
     ├ L2  net        出站网络适配：代理从环境来，loopback 永远直连（挂 VPN 时本地服务不断）
     └ L1  store      SQLite 封装：唯一落库出口
    L0 config 全局配置与常量 ｜ L0 model 数据模型 + 枚举常量

两处刻意的例外（别"修"掉）：
  - **函数内延迟 import**：下层偶尔要碰上层的能力（`scene` 用 `recall.char_overlap`、
    `distill` 用 `recall.bump_counters`、`shortterm` 用 `memo.judge_hits`）。
    放模块顶层就成环，放进函数体就不会。
  - **`dashboard` 谁都能 import**：它在最上面，本来就该碰全部。

二、读代码的顺序
    model → store → scene → shortterm → recall——五个读完，整条链路就有了。
    剩下的是加深：`distill`（谈多了怎么收）、`memo`（没发生的事怎么记）、
    `chat`（怎么拼进一次对话）、`dashboard`（怎么看见这一切）。

三、走到哪儿都得认的四条
  1. **数据不丢**：已写入的场景不被静默删除。库损坏 → 备份 + 报错、拒绝重建；
     归档只置 `archived=1`；老化只改 `status`。唯一真删是人点按钮，
     且走备份 + 摘引用 + 留痕（`Store.delete_scene`）。
  2. **降级不崩**：LLM 失败 → 保守默认值；没有向量 → 字符重叠。
     降级会变糙，但不该变哑——阈值也跟着降（见 `recall._c1_line`）。
  3. **S0 不可直接检索**：原文按天存文档（`data/raws/`），要它只能经场景编号下钻。
     例外是 `salvage`——那是人主动翻，不是自动路径。
  4. **该出手的事要看得见**：唤醒 / 跳过落库 / 工具调用 / 否决 / 合并 / 漂移
     都落一行 JSONL 到 `data/trace/`。「应该有但没发生」只能靠它回答。

四、注释怎么写
  **只写为什么，不写做了什么。** 做了什么一行代码就摆在那儿；被排除掉的那个
  更简单的写法、以及它为什么不行，才是半年后唯一想知道、而代码答不出来的东西。
  复述函数体的注释比没有更糟——它不会跟着改，然后开始骗人。

  模块头：为什么存在 + 关键取舍 + 边界（什么不该放这里）
  函数：一句话契约，再讲非显然处（返回空意味着什么、为什么这里保守）
  分支：凡「本可以发生但不发生」的（跳过 / 拒绝 / 没提 / 放弃）都要出声
  不写：签名里已有的类型、日期 + 人名的落款（那是 `git blame` 的事）
"""

